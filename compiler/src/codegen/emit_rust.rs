use crate::dirac::PortHamiltonianMatrices;
use crate::unroller::{InstructionTape, FmaOp};

pub struct CodeGenRust<'a> {
    pub model_name: &'a str,
    pub matrices: &'a PortHamiltonianMatrices,
    pub tape: &'a InstructionTape,
    pub dt: f64,
}

impl<'a> CodeGenRust<'a> {
    pub fn new(
        model_name: &'a str,
        matrices: &'a PortHamiltonianMatrices,
        tape: &'a InstructionTape,
        dt: f64,
    ) -> Self {
        Self {
            model_name,
            matrices,
            tape,
            dt,
        }
    }

    pub fn emit_code(&self) -> String {
        let n = self.matrices.n_states;
        let m = self.matrices.n_inputs;

        let mut out = String::new();
        out.push_str("//! Auto-generated by RT-MPBC Compiler.\n");
        out.push_str("//! Zero-allocation `#![no_std]` compiled physical model.\n\n");
        out.push_str("#![no_std]\n\n");

        out.push_str(&format!("pub const N_STATES: usize = {};\n", n));
        out.push_str(&format!("pub const N_INPUTS: usize = {};\n", m));
        out.push_str(&format!("pub const DT: f64 = {:.10};\n\n", self.dt));

        out.push_str("#[derive(Clone, Copy, Debug, Default)]\n");
        out.push_str("pub struct SimState {\n");
        out.push_str("    pub x: [f64; N_STATES],\n");
        out.push_str("    pub u: [f64; N_INPUTS],\n");
        out.push_str("    pub y: [f64; N_INPUTS],\n");
        out.push_str("    pub total_energy: f64,\n");
        out.push_str("}\n\n");

        out.push_str("impl SimState {\n");
        out.push_str("    pub const fn new() -> Self {\n");
        out.push_str("        Self {\n");
        out.push_str("            x: [0.0; N_STATES],\n");
        out.push_str("            u: [0.0; N_INPUTS],\n");
        out.push_str("            y: [0.0; N_INPUTS],\n");
        out.push_str("            total_energy: 0.0,\n");
        out.push_str("        }\n");
        out.push_str("    }\n\n");

        out.push_str("    pub fn energy(&self) -> f64 {\n");
        out.push_str("        let mut h = 0.0;\n");
        for i in 0..n {
            let q_ii = self.matrices.q[i][i];
            if q_ii.abs() > 1e-12 {
                out.push_str(&format!("        h += 0.5 * {:.12} * self.x[{}] * self.x[{}];\n", q_ii, i, i));
            }
        }
        out.push_str("        h\n");
        out.push_str("    }\n\n");

        out.push_str("    pub fn step(&mut self) {\n");
        out.push_str(&format!("        let mut b = [0.0f64; {}];\n", n.max(1)));
        out.push_str("        let x = self.x;\n");
        out.push_str("        let u = self.u;\n\n");
        out.push_str("        // Unrolled flat execution tape (Zero branches)\n");

        for op in &self.tape.ops {
            match op {
                FmaOp::SetConst { dest, val } => {
                    out.push_str(&format!("        {} = {:.12};\n", dest, val));
                }
                FmaOp::Fma { dest, src1, src2 } => {
                    out.push_str(&format!("        {} += {} * {};\n", dest, src1, src2));
                }
                FmaOp::Add { dest, src } => {
                    out.push_str(&format!("        {} += {};\n", dest, src));
                }
                FmaOp::Sub { dest, src } => {
                    out.push_str(&format!("        {} -= {};\n", dest, src));
                }
                FmaOp::Mul { dest, src1, src2 } => {
                    out.push_str(&format!("        {} = {} * {};\n", dest, src1, src2));
                }
                FmaOp::DivConst { dest, src, val } => {
                    out.push_str(&format!("        {} = {} / {:.12};\n", dest, src, val));
                }
            }
        }

        out.push_str("\n        for i in 0..N_STATES {\n");
        out.push_str("            self.x[i] = b[i];\n");
        out.push_str("        }\n");
        out.push_str("        self.total_energy = self.energy();\n");
        out.push_str("    }\n");
        out.push_str("}\n");

        out
    }
}

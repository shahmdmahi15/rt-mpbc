use crate::dirac::PortHamiltonianMatrices;
use crate::unroller::{InstructionTape, FmaOp};

pub struct CodeGenC<'a> {
    model_name: &'a str,
    matrices: &'a PortHamiltonianMatrices,
    tape: &'a InstructionTape,
    dt: f64,
}

impl<'a> CodeGenC<'a> {
    pub fn new(
        model_name: &'a str,
        matrices: &'a PortHamiltonianMatrices,
        tape: &'a InstructionTape,
        dt: f64,
    ) -> Self {
        Self {
            model_name,
            matrices,
            tape,
            dt,
        }
    }

    pub fn emit_header(&self) -> String {
        let name_upper = self.model_name.to_uppercase();
        let n = self.matrices.n_states;
        let m = self.matrices.n_inputs;

        let mut out = String::new();
        out.push_str(&format!("/**\n * @file {}.h\n", self.model_name));
        out.push_str(" * @brief Compiled zero-allocation Port-Hamiltonian model generated by RT-MPBC.\n");
        out.push_str(" * Standard: MISRA-C:2012 / C99 bare-metal compatible.\n */\n\n");
        out.push_str(&format!("#ifndef RTMPBC_COMPILED_{}_H\n", name_upper));
        out.push_str(&format!("#define RTMPBC_COMPILED_{}_H\n\n", name_upper));
        out.push_str("#include \"rtmpbc.h\"\n\n");

        out.push_str(&format!("#define {}_N_STATES {}\n", name_upper, n));
        out.push_str(&format!("#define {}_N_INPUTS {}\n", name_upper, m));
        out.push_str(&format!("#define {}_INPUTS_DIM {}\n", name_upper, m.max(1)));
        out.push_str(&format!("#define {}_DT {:.10}\n\n", name_upper, self.dt));

        out.push_str("/* State variable indexing */\n");
        for (i, name) in self.matrices.state_names.iter().enumerate() {
            out.push_str(&format!("#define {}_STATE_{} {}\n", name_upper, name.to_uppercase(), i));
        }
        out.push_str("\n");

        out.push_str("/* Input port indexing */\n");
        for (p, name) in self.matrices.input_names.iter().enumerate() {
            out.push_str(&format!("#define {}_INPUT_{} {}\n", name_upper, name.to_uppercase(), p));
        }
        out.push_str("\n");

        out.push_str(&format!("typedef struct {{\n"));
        out.push_str(&format!("    rtmpbc_real_t x[{}_N_STATES];\n", name_upper));
        out.push_str(&format!("    rtmpbc_real_t u[{}_INPUTS_DIM];\n", name_upper));
        out.push_str(&format!("    rtmpbc_real_t y[{}_INPUTS_DIM];\n", name_upper));
        out.push_str(&format!("    rtmpbc_real_t total_energy;\n"));
        out.push_str(&format!("}} {}_sim_t;\n\n", self.model_name));

        out.push_str(&format!("void {}_init({}_sim_t* sim);\n", self.model_name, self.model_name));
        out.push_str(&format!("void {}_step({}_sim_t* sim);\n", self.model_name, self.model_name));
        out.push_str(&format!("rtmpbc_real_t {}_energy(const {}_sim_t* sim);\n\n", self.model_name, self.model_name));

        out.push_str(&format!("#endif /* RTMPBC_COMPILED_{}_H */\n", name_upper));
        out
    }

    pub fn emit_source(&self) -> String {
        let name_upper = self.model_name.to_uppercase();
        let n = self.matrices.n_states;

        let mut out = String::new();
        out.push_str(&format!("/**\n * @file {}.c\n", self.model_name));
        out.push_str(" * @brief Compiled zero-branching unrolled execution kernel.\n */\n\n");
        out.push_str(&format!("#include \"{}.h\"\n", self.model_name));
        out.push_str("#include <string.h>\n\n");

        out.push_str(&format!("void {}_init({}_sim_t* sim) {{\n", self.model_name, self.model_name));
        out.push_str("    if (!sim) return;\n");
        out.push_str(&format!("    memset(sim->x, 0, {}_N_STATES * sizeof(rtmpbc_real_t));\n", name_upper));
        out.push_str(&format!("    memset(sim->u, 0, {}_INPUTS_DIM * sizeof(rtmpbc_real_t));\n", name_upper));
        out.push_str(&format!("    memset(sim->y, 0, {}_INPUTS_DIM * sizeof(rtmpbc_real_t));\n", name_upper));
        out.push_str("    sim->total_energy = 0.0;\n");
        out.push_str("}\n\n");

        out.push_str(&format!("rtmpbc_real_t {}_energy(const {}_sim_t* sim) {{\n", self.model_name, self.model_name));
        out.push_str("    rtmpbc_real_t h = 0.0;\n");
        for i in 0..n {
            let q_ii = self.matrices.q[i][i];
            if q_ii.abs() > 1e-12 {
                out.push_str(&format!("    h += 0.5 * {:.12} * sim->x[{}] * sim->x[{}];\n", q_ii, i, i));
            }
        }
        out.push_str("    return h;\n");
        out.push_str("}\n\n");

        out.push_str(&format!("void {}_step({}_sim_t* sim) {{\n", self.model_name, self.model_name));
        out.push_str("    if (!sim) return;\n");
        out.push_str("    rtmpbc_real_t b[256];\n");
        out.push_str("    const rtmpbc_real_t* x = sim->x;\n");
        out.push_str("    const rtmpbc_real_t* u = sim->u;\n");
        out.push_str("    (void)u;\n");
        out.push_str("    (void)x;\n\n");
        out.push_str("    /* Flat unrolled instruction tape (Zero Branches, SIMD-friendly) */\n");

        for op in &self.tape.ops {
            match op {
                FmaOp::SetConst { dest, val } => {
                    out.push_str(&format!("    {} = {:.12};\n", dest, val));
                }
                FmaOp::Fma { dest, src1, src2 } => {
                    out.push_str(&format!("    {} += {} * {};\n", dest, src1, src2));
                }
                FmaOp::Add { dest, src } => {
                    out.push_str(&format!("    {} += {};\n", dest, src));
                }
                FmaOp::Sub { dest, src } => {
                    out.push_str(&format!("    {} -= {};\n", dest, src));
                }
                FmaOp::Mul { dest, src1, src2 } => {
                    out.push_str(&format!("    {} = {} * {};\n", dest, src1, src2));
                }
                FmaOp::DivConst { dest, src, val } => {
                    out.push_str(&format!("    {} = {} / {:.12};\n", dest, src, val));
                }
            }
        }

        out.push_str("\n    /* Direct state update */\n");
        for i in 0..n {
            out.push_str(&format!("    sim->x[{}] = b[{}];\n", i, i));
        }

        out.push_str(&format!("\n    sim->total_energy = {}_energy(sim);\n", self.model_name));
        out.push_str("}\n");

        out
    }
}
